#!/usr/bin/env python3
"""Turn finished run artifacts into the paper table and the run log.

Reads supplementary/benchmark_results.csv plus supplementary/runs/*/run_config.json,
refuses to touch paper/main.tex unless all 12 (model family, epoch) rows are present.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "supplementary" / "benchmark_results.csv"
RUNS = ROOT / "supplementary" / "runs"
RUN_LOG = ROOT / "supplementary" / "run_log.csv"
MANIFEST = ROOT / "dataset" / "Annotated" / "split" / "split_manifest.csv"
PAPER = ROOT / "paper" / "main.tex"

FAMILIES = ["YOLOv7", "YOLOv8", "YOLOv9", "YOLOv10", "YOLO11", "YOLO26"]
VARIANTS = {"YOLOv7": "tiny", "YOLOv8": "n", "YOLOv9": "t", "YOLOv10": "n", "YOLO11": "n", "YOLO26": "n"}
EPOCHS = (15, 30)
BEGIN = "% RESULTS-TABLE-BEGIN"
END = "% RESULTS-TABLE-END"
RUN_LOG_FIELDS = [
    "run_started_utc", "model_family", "variant", "epochs", "saved_epochs", "dataset_yaml",
    "split_manifest_sha256", "framework", "framework_version", "torch_version", "python_version",
    "gpu", "seed", "batch_size", "image_size", "status", "run_directory", "notes",
]
METRICS = ["precision", "recall", "f1", "map50", "map50_95"]


def alias(family: str) -> str:
    """Map the spellings the two runners write ("yolov8", "YOLOv8") onto the paper's names."""
    key = family.strip().lower().replace(" ", "")
    return {name.lower(): name for name in FAMILIES}.get(key, family)


def load_results(path: Path) -> dict[tuple[str, int], dict[str, str]]:
    if not path.is_file() or path.stat().st_size == 0:
        raise SystemExit(f"No results file yet: {path}")
    with path.open(encoding="utf-8") as stream:
        rows = list(csv.DictReader(stream))
    table = {}
    for row in rows:
        try:
            family = alias(row["model_family"])
            epoch = int(float(row["epoch"]))
        except (KeyError, ValueError):
            continue
        table[(family, epoch)] = row
    return table


def check_complete(table: dict[tuple[str, int], dict[str, str]]) -> list[str]:
    problems = []
    for family in FAMILIES:
        for epoch in EPOCHS:
            row = table.get((family, epoch))
            if row is None:
                problems.append(f"{family} epoch {epoch}: no row")
                continue
            if str(row.get("classes", "")).strip() != "1":
                problems.append(f"{family} epoch {epoch}: classes={row.get('classes')!r}, expected 1")
            for metric in METRICS:
                try:
                    value = float(row[metric])
                except (KeyError, TypeError, ValueError):
                    problems.append(f"{family} epoch {epoch}: {metric} is not a number")
                    continue
                if not 0.0 <= value <= 1.0:
                    problems.append(f"{family} epoch {epoch}: {metric}={value} outside [0, 1]")
    return problems


def tex_rows(table: dict[tuple[str, int], dict[str, str]]) -> list[str]:
    lines = [f"{BEGIN} generated by scripts/build_submission.py; do not hand-edit between these markers"]
    for family in FAMILIES:
        for epoch in EPOCHS:
            row = table[(family, epoch)]
            params = int(float(row["trainable_parameters"]))
            lines.append(
                f"{family} & {VARIANTS[family]} & {epoch} & 1 & {params:,} & "
                + " & ".join(f"{float(row[m]):.4f}" for m in METRICS)
                + r" \\"
            )
    lines.append(END)
    return lines


def inject(paper: Path, rows: list[str]) -> str:
    text = paper.read_text(encoding="utf-8")
    start = text.find(BEGIN)
    end = text.find(END)
    if start < 0 or end < 0 or end < start:
        raise SystemExit(f"Table markers not found in {paper}; expected {BEGIN} and {END}.")
    end += len(END)
    return text[:start] + "\n".join(rows) + text[end:]


def manifest_hash() -> str:
    if not MANIFEST.is_file():
        return ""
    return hashlib.sha256(MANIFEST.read_bytes()).hexdigest()


def run_log_rows(table: dict[tuple[str, int], dict[str, str]], runs: Path) -> list[dict[str, str]]:
    digest = manifest_hash()
    rows = []
    for family in FAMILIES:
        path = runs / family.lower() / "run_config.json"
        if not path.is_file():
            path = next(iter(sorted(runs.glob(f"**/{family.lower()}_run_config.json"))), path)
        config = json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}
        ran = [epoch for epoch in EPOCHS if (family, epoch) in table]
        rows.append({
            "run_started_utc": str(config.get("started_utc", ""))[:19],
            "model_family": family,
            "variant": str(config.get("variant") or config.get("checkpoint") or VARIANTS[family]),
            "epochs": str(config.get("epochs", 30)),
            "saved_epochs": str(config.get("saved_epochs", [15, 30])),
            "dataset_yaml": str(config.get("dataset_yaml", "")),
            "split_manifest_sha256": digest,
            "framework": "ultralytics" if family != "YOLOv7" else "yolov7-upstream",
            "framework_version": str(config.get("framework_version", "unknown" if family == "YOLOv7" else "")),
            "torch_version": str(config.get("torch_version", "")),
            "python_version": str(config.get("python_version", "")),
            "gpu": str(config.get("gpu", "")),
            "seed": str(config.get("seed", "")),
            "batch_size": str(config.get("batch_size", "")),
            "image_size": str(config.get("image_size", 640)),
            "status": "complete" if len(ran) == len(EPOCHS) else ("partial" if ran else "config only"),
            "run_directory": str(config.get("run_directory", runs / family.lower())),
            "notes": ", ".join(f"epoch {epoch}" for epoch in ran),
        })
    return rows


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=RESULTS)
    parser.add_argument("--paper", type=Path, default=PAPER)
    parser.add_argument("--run-log", type=Path, default=RUN_LOG)
    parser.add_argument("--runs-dir", type=Path, default=RUNS)
    parser.add_argument("--dry-run", action="store_true", help="print the table and run log instead of writing")
    parser.add_argument("--skip-paper", action="store_true", help="refresh only the run log")
    args = parser.parse_args()

    table = load_results(args.results)
    problems = check_complete(table)
    if problems:
        print("Results are not complete; nothing was written:", file=sys.stderr)
        for problem in problems:
            print(f"  {problem}", file=sys.stderr)
        return 1

    rows = tex_rows(table)
    log = run_log_rows(table, args.runs_dir)

    if args.dry_run:
        print("\n".join(rows))
        print()
        writer = csv.DictWriter(sys.stdout, fieldnames=RUN_LOG_FIELDS)
        writer.writeheader()
        writer.writerows(log)
        return 0

    updated = args.paper.read_text(encoding="utf-8")
    if not args.skip_paper:
        updated = inject(args.paper, rows)
        args.paper.write_text(updated, encoding="utf-8")
        print(f"Injected 12 result rows into {args.paper}.")
    with args.run_log.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=RUN_LOG_FIELDS)
        writer.writeheader()
        writer.writerows(log)
    print(f"Wrote {args.run_log} with {len(log)} rows.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
